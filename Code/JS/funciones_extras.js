const productGrid = document.querySelector("#product-grid");

function createProductCard(product) {
  const card = document.createElement("article");
  card.className = "product-card";

  const cover = document.createElement("div");
  cover.className = "product-cover";
  cover.style.setProperty("--cover-color", product.coverColor || "#657d67");

  const initials = document.createElement("span");
  initials.className = "cover-initials";
  initials.setAttribute("aria-hidden", "true");
  initials.textContent = product.title
    .split(/\s+/)
    .slice(0, 2)
    .map((word) => word.charAt(0))
    .join("")
    .toLocaleUpperCase("es");

  cover.append(initials);

  if (product.image) {
    const image = document.createElement("img");
    image.src = product.image;
    image.alt = product.imageAlt || "";
    image.loading = "lazy";

    // Si no encuentra la imagen, permanece visible la portada de color.
    image.addEventListener("error", () => image.remove(), { once: true });
    cover.append(image);
  }

  if (product.category) {
    const category = document.createElement("span");
    category.className = "category-badge";
    category.textContent = product.category;
    cover.append(category);
  }

  const content = document.createElement("div");
  content.className = "product-content";

  const year = document.createElement("p");
  year.className = "product-year";
  year.textContent = product.year || "Publicación";

  const title = document.createElement("h2");
  title.className = "product-title";
  title.textContent = product.title;

  const description = document.createElement("p");
  description.className = "product-description";
  description.textContent = product.description;

  content.append(year, title, description);

  const actions = document.createElement("div");
  actions.className = "product-actions";

  const link = document.createElement("a");
  link.className = "product-link";
  link.href = product.productUrl;
  link.setAttribute("aria-label", `Ver producto: ${product.title}`);
  link.textContent = "Ver producto";

  actions.append(link);
  content.append(actions);
  card.append(cover, content);

  return card;
}

productGrid.replaceChildren(...products.map(createProductCard));
